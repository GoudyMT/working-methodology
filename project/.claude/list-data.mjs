// The improvement list and the roadmap as data (T4 slice 2, 1.35.0); state.mjs runs it. On 1.34.0 the workbench list
// held 339 rows in 9 table shapes, no row said who caught it (J4) and no number said where it was measured (J3), and
// the counts were recounted by hand at every closeout. Now each row is one line of _List.jsonl with one tag, and the
// roadmap steps sit in _State.json; the roadmap, counts and rows views are generated between list markers.
//
// A row: { id, title, short?, tag, at?, severity, origin?, caught_by?, escaped?, measured?, note?, section?, detail? }
//   short      the row in at most 60 characters (K68, 1.36.0): the short view shows it; a new row must carry one
//   tag        one of TAGS; "at" says where (a release for done, a step for later, a build for next)
//   origin     who found it: real-use (a project using the kit), owner, outside (another method), self (the kit on itself)
//   caught_by  which layer caught it (J4); a row that is done or closed must name one
//   measured   where its numbers come from (J3); a row with a number must name one
// A row moved in by list import owes those labels to the one-time audit (list audit) instead of failing check, but
// only while it is as it was imported: state.mjs keeps each imported row's tag and a hash of its text in _State.json
// (list_import), so a row whose tag or text changed since owes its labels like a new one, and a mark typed into a row
// buys nothing.
import crypto from 'node:crypto';

export const LIST = '_List.jsonl';
// blocked (K69, 1.36.0): a checkbox roadmap's [!] box, held by something outside the row.
export const TAGS = ['done', 'closed', 'now', 'next', 'blocked', 'later', 'after', 'separate', 'owner', 'standing', 'plan'];
const CLOSED = ['done', 'closed'];
// The order open rows are worked in: a tag for this build before a later step, then what waits on the owner.
const WORK_ORDER = ['now', 'next', 'blocked', 'later', 'owner', 'separate', 'after', 'standing', 'plan'];
// K69: a checkbox roadmap's boxes and the tags they stand for, both ways ([~] deferred is after; a closed row shows so).
const BOX_TAG = { x: 'done', X: 'done', '/': 'now', ' ': 'later', '!': 'blocked', '~': 'after' };
const TAG_BOX = { done: 'x', now: '/', next: ' ', later: ' ', blocked: '!', owner: '!', after: '~', closed: '~', separate: ' ', standing: ' ', plan: ' ' };
export const BOX_LINE = /^(\s*)- \[([ xX/!~])\] (.+)$/;
export const ORIGINS = ['real-use', 'owner', 'outside', 'self'];
export const CAUGHT = ['sweep', 'ci', 'recall', 'plan-check', 'review', 'guard', 'owner', 'real-use', 'self'];
export const MEASURED = ['throwaway', 'real-use', 'ci', 'agent-report', 'estimate', 'quote'];
export const SEVERITIES = ['critical', 'high', 'medium', 'low', 'to set'];
// A row with no severity yet ranks after high, ahead of medium: an unrated row may be the worst one.
const SEVERITY_ORDER = ['critical', 'high', 'to set', 'medium', 'low'];
const ID = /^[A-Za-z][A-Za-z0-9.-]{0,39}$/;
export const SHORT = 60;
const BLOCKS = ['roadmap', 'counts', 'rows', 'archive', 'boxes'];
const BEGIN = (name) => `<!-- list:begin ${name}: generated by .claude/state.mjs from ${LIST} and _State.json; change it with state.mjs, never by hand -->`;
const END = '<!-- list:end -->';
const MARKER = /<!--\s*list:/;
// A fence at any indent: one inside a list item is still a fence (1.36.0 sweep).
const FENCE = /^\s*(```|~~~)/;
const LIST_ITEM = /^\s*([-*+]|\d+[.)])\s/;
const indent = (l) => /^\s*/.exec(l)[0].replace(/\t/g, '    ').length;
// A version heading with its state in brackets ("v1 - "Live demo" (IN PROGRESS)") is a roadmap step. Read by hand,
// not by one regex: two lazy groups over a long heading backtrack without bound (1.36.0 sweep).
function stepOf(h) {
	if (!h || !h.endsWith(')')) return null;
	const o = h.lastIndexOf(' (');
	const d = o > 0 ? h.slice(0, o).indexOf(' - ') : -1;
	if (d <= 0 || h.slice(o + 2, -1).includes(')')) return null;
	const carries = h.slice(d + 3, o).trim().replace(/^"/, '').replace(/"$/, '').trim();
	// Spacing read as one space, as the state keeps a step's name (the 1.36.1 sweep: "A  B" was placed at no step).
	const one = (x) => x.replace(/\s+/g, ' ').trim();
	return carries ? { step: one(h.slice(0, d)), carries: one(carries), state: one(h.slice(o + 2, -1)) } : null;
}
const clip = (s) => (s.length > SHORT ? `${s.slice(0, SHORT - 3).replace(/[\s.,;:]+$/, '')}...` : s);
// Any control character, line or paragraph separator, or bidi override: none belongs in one line of list text.
const CONTROL = /[\u0000-\u001f\u007f-\u009f\u2028\u2029\u202a-\u202e\u2066-\u2069]/;
const CONTROLS = /[\u0000-\u001f\u007f-\u009f\u2028\u2029\u202a-\u202e\u2066-\u2069]+/g;
// A value quoted in a message: one line, short, with no control character.
const show = (v) => JSON.stringify(String(v ?? '')).replace(CONTROLS, ' ').slice(0, 40);
const sha = (t) => crypto.createHash('sha256').update(t).digest('hex').slice(0, 16);

/** The rows, or a reason the file is not a clean list. A missing file is an empty list with exists false. */
export function loadList(io) {
	if (io.linked && io.linked(LIST)) return { why: `${LIST} is a link or not a plain file, which state.mjs never reads through` };
	const text = io.readText(LIST);
	if (text === null) return { rows: [], exists: false };
	const rows = [];
	const lines = text.split(/\r?\n/).filter((l) => l.trim());
	for (let i = 0; i < lines.length; i++) {
		let r;
		try { r = JSON.parse(lines[i]); } catch { return { why: `${LIST} line ${i + 1} is not JSON` }; }
		const bad = shape(r, rows);
		if (bad) return { why: `${LIST} line ${i + 1}: ${bad}` };
		rows.push(r);
	}
	return { rows, exists: true };
}

const KEYS = ['id', 'title', 'short', 'tag', 'at', 'severity', 'origin', 'caught_by', 'escaped', 'measured', 'note', 'section', 'detail', 'verify'];
/** What is wrong with a row's shape (not its owed labels), or null. */
function shape(r, rows) {
	if (!r || typeof r !== 'object' || Array.isArray(r)) return 'not an object';
	if (typeof r.id !== 'string' || !ID.test(r.id)) return `the id ${show(r.id)} is not letters, digits, dots and dashes`;
	const extra = Object.keys(r).find((k) => !KEYS.includes(k));
	if (extra) return `${r.id}: ${show(extra)} is not a row field (${KEYS.join(', ')})`;
	if (rows.some((x) => x.id === r.id)) return `${r.id} is given twice`;
	if (typeof r.title !== 'string' || !r.title.trim()) return `${r.id} has no title`;
	if (r.short != null && (typeof r.short !== 'string' || !r.short.trim())) return `${r.id}: the short name is not text`;
	if (r.short != null && r.short.length > SHORT) return `${r.id}: the short name is over ${SHORT} characters`;
	if (!TAGS.includes(r.tag)) return `${r.id}: tag ${show(r.tag)} is not one of ${TAGS.join(', ')}`;
	if (!SEVERITIES.includes(r.severity)) return `${r.id}: severity ${show(r.severity)} is not one of ${SEVERITIES.join(', ')}`;
	if (r.origin != null && !ORIGINS.includes(r.origin)) return `${r.id}: origin ${show(r.origin)} is not one of ${ORIGINS.join(', ')}`;
	if (r.caught_by != null && !CAUGHT.includes(r.caught_by)) return `${r.id}: caught_by ${show(r.caught_by)} is not one of ${CAUGHT.join(', ')}`;
	if (r.measured != null && !MEASURED.includes(r.measured)) return `${r.id}: measured ${show(r.measured)} is not one of ${MEASURED.join(', ')}`;
	if (r.escaped != null && typeof r.escaped !== 'boolean') return `${r.id}: escaped is not true or false`;
	for (const k of ['at', 'note', 'section', 'verify']) if (r[k] != null && typeof r[k] !== 'string') return `${r.id}: ${k} is not text`;
	if (r.detail != null && (typeof r.detail !== 'object' || Array.isArray(r.detail) || Object.values(r.detail).some((v) => typeof v !== 'string'))) return `${r.id}: detail is not a set of text cells`;
	const texts = [r.title, r.short, r.at, r.note, r.section, r.verify, ...Object.keys(r.detail || {}), ...Object.values(r.detail || {})].filter((x) => x != null);
	if (texts.some((x) => CONTROL.test(x))) return `${r.id}: a text field holds a line break or a control character`;
	return null;
}

// J3: a number someone measured, as against an id, a version, a date, a time or a file line.
const NOT_MEASURES = [/\b\d{4}-\d{2}-\d{2}\b/g, /\b\d{1,2}:\d{2}(:\d{2})?\b/g, /\bv?\d+\.\d+(\.\d+)+\b/g, /\b[A-Za-z]+[-.]?\d+[a-z]?(\.\d+)?(-\d+)?\b/g, /(#|PR |pr |build |step |rule |line |row |item |stage |part |option |trial |round |run )\d+\b/g, /:\d+(-\d+)?\b/g];
const textOf = (r) => [r.title, r.note || '', ...Object.values(r.detail || {})].join(' ');
export const holdsNumber = (r) => /\d/.test(NOT_MEASURES.reduce((t, re) => t.replace(re, ' '), textOf(r)));

/** The import's record of a row: its tag and a hash of its text, kept in _State.json (list_import). */
export const importMark = (r) => [r.tag, sha(textOf(r))];
// What a row owes the one-time audit instead of check: a catcher while its tag is the imported one, a measure label
// while its text is the imported text.
const debt = (r, marks) => {
	const m = marks && Object.hasOwn(marks, r.id) ? marks[r.id] : null;
	return { catcher: !!m && m[0] === r.tag, measure: !!m && m[1] === sha(textOf(r)) };
};

/** The labels a row still owes: a catcher on a closed row, a measure label on a number. */
function owed(r) {
	const out = [];
	if (CLOSED.includes(r.tag) && !r.caught_by) out.push('caught-by');
	if (holdsNumber(r) && !r.measured) out.push('measured');
	return out;
}

// One table cell: no line break of any kind and no comment marker, so row text can never end a block or start one;
// an @ is escaped, so a cell never reads as a file import.
const cell = (s) => String(s ?? '').replace(CONTROLS, ' ').replace(/<!--/g, '<! --').replace(/-->/g, '-- >').replace(/\|/g, '\\|').replace(/@/g, '\\@');
const tagText = (r) => `**[${r.tag.toUpperCase()}${r.at ? ` ${cell(r.at).replace(/\]/g, ')')}` : ''}]**`;
const dash = (s) => (String(s ?? '').trim() ? s : '-');

// A markdown table row's cells, split on pipes that are not escaped.
const cells = (line) => line.trim().replace(/^\|/, '').replace(/(?<!\\)\|$/, '').split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|'));
const TAG_IN = /\*\*\[([A-Za-z]+)(?: ([^\]]*))?\]\*\*/;
const sev = (s) => { const m = String(s).toLowerCase().match(/\b(critical|high|medium|low)\b/); return m ? m[1] : 'to set'; };
const SEPARATOR = /^\|[\s:|-]+\|$/;

/**
 * Read a markdown list whole: every table with an ID and a Status column becomes rows, under the headings it sits in;
 * a table headed Build | Release | ... | State becomes the roadmap steps. It refuses the whole file on any row or table
 * it cannot move (no tag, an unknown tag, an id twice, a cell too many or too few, a row outside a table, an indented
 * table, a table with an ID or a Status column but not both), so a half list is never written. Fenced code is skipped.
 */
export function parseMarkdown(text, { taken = [] } = {}) {
	// Split on LF alone, so line i here is line i of the file whatever its endings; a CR is not part of the text.
	const lines = text.split('\n').map((l) => l.replace(/\r$/, ''));
	const rows = [];
	const steps = [];
	const faults = [];
	const heads = [];
	// K69: checkbox lines, read whole and given ids at the end (after any table rows, so no id is taken twice).
	const boxes = [];
	let generated = false;
	let fence = null;
	let comment = false;
	// Whether the last line with text was a list item or a line indented under one: only there is an indented box a
	// box; anywhere else four spaces make it code (1.36.0 sweep).
	let inList = false;
	// The box whose own lines (prose, a plain sub-bullet) the next deeper lines are: they move with it, into its note.
	let cur = null;
	for (let i = 0; i < lines.length; i++) {
		const l = lines[i];
		const f = FENCE.exec(l);
		if (fence) { if (f && f[1] === fence) fence = null; continue; }
		// A generated block is a view of data already held: never read back as rows.
		if (generated) { if (l === END) generated = false; continue; }
		if (!l.trim()) continue;
		// An HTML comment is hidden text, not a box: skip it whole.
		if (comment) { if (l.includes('-->')) comment = false; continue; }
		if (/^<!-- list:begin /.test(l)) { generated = i + 1; cur = null; continue; }
		if (/^\s*<!--/.test(l)) { comment = !/-->/.test(l.slice(l.indexOf('<!--') + 4)); cur = null; continue; }
		if (f) { fence = f[1]; cur = null; continue; }
		const h = l.match(/^(#{2,4}) (.+)$/);
		if (h) { heads.length = h[1].length - 2; heads[h[1].length - 2] = h[2].trim(); cur = null; inList = false; continue; }
		const b = BOX_LINE.exec(l);
		const deep = indent(l) >= 4;
		if (b && (!deep || inList)) {
			cur = { line: i, depth: b[1].replace(/\t/g, '  ').length, tag: BOX_TAG[b[2]], title: b[3].trim(), section: heads.filter(Boolean).join(' / '), step: stepOf(heads[0]), more: [], moreLines: [] };
			boxes.push(cur);
			inList = true;
			continue;
		}
		if (cur && b == null && indent(l) > cur.depth) { cur.more.push(l.trim()); cur.moreLines.push(i); continue; }
		cur = null;
		if (deep && !inList) continue;
		if (LIST_ITEM.test(l)) inList = true;
		else if (!/^\s/.test(l)) inList = false;
		if (b) continue;
		if (/^\s+\|/.test(l)) { faults.push(`an indented table row at line ${i + 1}: move the table to the left edge`); continue; }
		if (!/^\|/.test(l)) continue;
		if (!SEPARATOR.test(lines[i + 1] || '')) {
			// A row with no header above it: markdown shows it as plain text, so it would be dropped unseen.
			if (!SEPARATOR.test(l.trim())) faults.push(`${cells(l)[0]} is outside any table (line ${i + 1}): a blank line or a missing header splits it from its table`);
			continue;
		}
		const head = cells(l);
		const at = i + 1;
		const body = [];
		const lineNo = [];
		for (i += 2; i < lines.length && /^\|/.test(lines[i]); i++) { body.push(cells(lines[i])); lineNo.push(i + 1); }
		// A line right under the table with pipes but no leading one is a row the table lost.
		if (i < lines.length && /\S/.test(lines[i]) && (lines[i].match(/(?<!\\)\|/g) || []).length >= 2) faults.push(`line ${i + 1} looks like a row of the table above but does not start with a pipe`);
		i--;
		const section = heads.filter(Boolean).join(' / ');
		const col = (re) => head.findIndex((c) => re.test(c));
		const twice = head.find((c, k) => head.indexOf(c) !== k);
		if (twice) { faults.push(`the table at line ${at} names the column ${show(twice)} twice`); continue; }
		const wrong = body.map((c, n) => [c, n]).filter(([c]) => c.length !== head.length);
		for (const [c, n] of wrong) faults.push(`${c[0] || '(empty)'} at line ${lineNo[n]} has ${c.length} cells against ${head.length} in its header (an unescaped pipe?)`);
		if (wrong.length) continue;
		if (/^build$/i.test(head[0]) && /^release$/i.test(head[1] || '')) {
			const st = col(/^state$/i);
			const rest = head.map((name, k) => [name, k]).filter(([, k]) => k > 1 && k !== st);
			body.forEach((c, n) => {
				if (!c[0]) { faults.push(`the roadmap row at line ${lineNo[n]} has no step`); return; }
				if (steps.some((s) => s.step === c[0] && s.release === (c[1] || ''))) { faults.push(`roadmap step ${c[0]} ${c[1] || ''} is given twice (line ${lineNo[n]})`); return; }
				// The first other column is what the step carries; any further one is kept in it, named.
				const carries = rest.map(([name, k], j) => (j === 0 ? c[k] : c[k] ? `${name}: ${c[k]}` : '')).filter(Boolean).join('; ');
				steps.push({ step: c[0], release: c[1] || '', carries, state: st >= 0 ? c[st] || '' : '', table: true });
			});
			continue;
		}
		const id = col(/^id$/i);
		const status = col(/^status$/i);
		if (id < 0 && status < 0) continue;
		if (id < 0 || status < 0) { faults.push(`the table at line ${at} has ${id < 0 ? 'a Status column but no ID' : 'an ID column but no Status'} column, so its rows cannot be moved`); continue; }
		const severity = col(/^severity/i);
		const title = head.findIndex((c, k) => ![id, status, severity].includes(k));
		body.forEach((c, n) => {
			const where = `line ${lineNo[n]}`;
			const m = TAG_IN.exec(c[status] || '');
			if (!m) { faults.push(`${c[id]} has no tag: its status must start with **[TAG ...]** (${where})`); return; }
			const tag = m[1].toLowerCase() === 'shipped' ? 'done' : m[1].toLowerCase();
			if (!TAGS.includes(tag)) { faults.push(`${c[id]}: tag ${m[1]} is not one of ${TAGS.map((t) => t.toUpperCase()).join(', ')} (${where})`); return; }
			const detail = {};
			head.forEach((name, k) => { if (![id, title, status].includes(k) && c[k] && c[k] !== '-' && !(k === severity && SEVERITIES.includes(c[k]))) detail[name] = c[k]; });
			const r = { id: c[id], title: title >= 0 ? c[title] || '' : '', tag, severity: severity >= 0 ? sev(c[severity]) : 'to set' };
			if (section) r.section = section;
			if (m[2]) r.at = m[2].trim();
			const note = (c[status] || '').replace(m[0], '').trim();
			if (note) r.note = note;
			if (Object.keys(detail).length) r.detail = detail;
			const bad = shape(r, rows);
			if (bad) { faults.push(`${bad} (${where})`); return; }
			rows.push(r);
		});
	}
	let n = 0;
	const parents = [];
	for (const x of boxes) {
		// An id the list already holds is skipped too (1.36.1: boxes may join a list that has rows).
		do n++; while (rows.some((r) => r.id === `R${n}`) || taken.includes(`R${n}`));
		const id = `R${n}`;
		// An indented box keeps the box above it at a lower depth as its parent.
		while (parents.length && parents[parents.length - 1].depth >= x.depth) parents.pop();
		const up = parents[parents.length - 1];
		// A child row carries its parent's short name, so it reads alone in the short view.
		const r = { id, title: x.title, short: up ? clip(`${up.short}: ${derive(x.title).short}`) : derive(x.title).short, tag: x.tag, severity: 'to set' };
		if (x.section) r.section = x.section;
		if (x.step) {
			r.at = x.step.step;
			if (!steps.some((s) => s.step === x.step.step && s.release === '')) steps.push({ step: x.step.step, release: '', carries: x.step.carries, state: x.step.state });
		}
		const note = [up ? `under ${up.id}` : '', x.more.join(' / ')].filter(Boolean).join('; ');
		if (note) r.note = note;
		const bad = shape(r, rows);
		if (bad) { faults.push(`${bad} (line ${x.line + 1})`); continue; }
		rows.push(r);
		parents.push({ id, depth: x.depth, short: r.short });
	}
	if (fence) faults.push('a code fence never closes, so the rest of the file was not read');
	if (comment) faults.push('an HTML comment never closes, so the rest of the file was not read');
	if (generated) faults.push(`the generated block at line ${generated} never closes (no ${END}), so the rest of the file was not read`);
	if (!rows.length && !faults.length) faults.push('no table with an ID column and a Status column, and no checkbox list, was found');
	return { rows, steps, faults, boxLines: boxes.flatMap((x) => [x.line, ...x.moreLines]).sort((a, b) => a - b), tableRows: rows.length - boxes.length };
}

export const serialize = (rows) => rows.map((r) => JSON.stringify(r)).join('\n') + (rows.length ? '\n' : '');

// T11: open rows in work order (this build's first), then by severity; at the same severity a row from a real project
// ranks above one the owner asked for, then another method's, then the kit's own finds, then one with no origin set.
const rank = (r) => [WORK_ORDER.indexOf(r.tag), SEVERITY_ORDER.indexOf(r.severity), r.origin ? ORIGINS.indexOf(r.origin) : ORIGINS.length];
export function ranked(rows) {
	return rows.filter((r) => !CLOSED.includes(r.tag)).map((r, i) => [r, i]).sort(([a, i], [b, j]) => {
		const [x, y] = [rank(a), rank(b)];
		return x[0] - y[0] || x[1] - y[1] || x[2] - y[2] || i - j;
	}).map(([r]) => r);
}
const plain = (s) => String(s ?? '').replace(CONTROLS, ' ');

// K68 (1.36.0): the short view. On 1.35.0 `list` printed each row's whole title, and three rows filled a phone
// screen. A row's short name is stored (a title clipped on the fly read badly on rows with no bold lead); a row from
// before 1.36.0 shows its bold lead, or its first clause clipped, until list shorten stores one.
export function derive(title) {
	const b = /^\*\*(.+?)\*\*/.exec(plain(title));
	let s = (b ? b[1] : plain(title).split(/[;:]\s|\.\s|\s\(/)[0]).replace(/[`*]/g, '').replace(/\s+/g, ' ').trim().replace(/\.$/, '');
	if (s.length > SHORT) s = `${s.slice(0, SHORT - 3).replace(/[\s.,;:]+$/, '')}...`;
	return { short: s || plain(title).slice(0, SHORT), bold: !!b };
}
export const shortOf = (r) => plain(r.short ?? derive(r.title).short);
// A build named by its number ("build 10 (1.36.0)" is b10), so the place fits its column.
const place = (at) => { const s = plain(at || '-'); const b = /^build (\S+)/i.exec(s); return (b ? `b${b[1]}` : s).slice(0, 8); };
const sevText = (s) => (s === 'to set' ? '-' : s);

/** The short view: a header, one line per row (id, tag, place, severity, origin, short name), and a closing count. */
export function table(rows, { all = false } = {}) {
	const w = Math.max(2, ...rows.map((r) => r.id.length)) + 2;
	const pad = (s, n) => String(s).padEnd(n);
	const out = [`${pad('ID', w)}${pad('TAG', 9)}${pad('STEP', 9)}${pad('SEV', 9)}${pad('FROM', 9)}TITLE`];
	for (const r of rows) out.push(`${pad(r.id, w)}${pad(r.tag, 9)}${pad(place(r.at), 9)}${pad(sevText(r.severity), 9)}${pad(r.origin || '-', 9)}${shortOf(r)}`);
	out.push(`${rows.length} ${all ? 'row(s)' : 'open'}. Whole row: state.mjs item <id> | full titles: list --full | every row: list --all`);
	return out;
}
/** The agent view of one row: the fields to sort and pick by, and where the rest is. */
export const agent = (r) => ({ id: r.id, tag: r.tag, at: r.at ?? null, sev: r.severity, origin: r.origin ?? null, short: shortOf(r), more: `item ${r.id}` });

export const line = (r) => plain(`${r.id} [${r.tag.toUpperCase()}${r.at ? ` ${r.at}` : ''}] ${r.severity}${r.origin ? `, ${r.origin}` : ''}: ${r.title}`);

/** J4 and T11 at a glance: who caught the closed rows, how many escaped a gate, and found-to-shipped by origin. */
export function caught(rows) {
	const closed = rows.filter((r) => CLOSED.includes(r.tag));
	const by = CAUGHT.map((c) => [c, closed.filter((r) => r.caught_by === c).length]).filter(([, n]) => n);
	const none = closed.filter((r) => !r.caught_by).length;
	const out = [`Caught by: ${by.map(([c, n]) => `${c} ${n}`).join(', ') || 'none named'}${none ? `; not named ${none}` : ''}; escaped a gate: ${closed.filter((r) => r.escaped).length} of ${closed.length}`];
	const origins = [...ORIGINS, null].map((o) => {
		const mine = rows.filter((r) => (r.origin || null) === o);
		const n = (t) => mine.filter((r) => r.tag === t).length;
		return mine.length ? `${o || 'not set'} ${mine.length} found, ${n('done')} done, ${n('closed')} closed, ${mine.length - n('done') - n('closed')} open` : null;
	}).filter(Boolean);
	out.push(`Found to shipped by origin: ${origins.join('; ') || 'no rows'}`);
	return out;
}

/** The rows still owed a label, one line each: the one-time catch-rate, measure and origin audit. */
export const audit = (rows) => rows.flatMap((r) => {
	const need = [...(r.origin ? [] : ['origin']), ...owed(r), ...(r.short == null ? ['short'] : [])];
	return need.length ? [plain(`${r.id} owes ${need.join(', ')}: ${r.title.slice(0, 80)}`)] : [];
});

/** Faults and notes for check: labels owed by rows added or changed since the import fail; imported ones are counted. */
export function faultsOf(rows, marks = {}) {
	const faults = [];
	let noCatch = 0;
	let noMeasure = 0;
	for (const r of rows) {
		const d = debt(r, marks);
		for (const k of owed(r)) {
			if (k === 'caught-by' && d.catcher) { noCatch++; continue; }
			if (k === 'measured' && d.measure) { noMeasure++; continue; }
			faults.push(k === 'measured' ? `${r.id} holds a number but names no measured label (${MEASURED.join(', ')}): node .claude/state.mjs item set ${r.id} measured <label>` : `${r.id} is ${r.tag} but names no catcher: node .claude/state.mjs item set ${r.id} caught-by <${CAUGHT.join('|')}>`);
		}
	}
	const notes = [];
	if (noCatch) notes.push(`${noCatch} imported done or closed row(s) name no catcher yet (node .claude/state.mjs list audit)`);
	if (noMeasure) notes.push(`${noMeasure} imported row(s) hold a number with no measure label yet (node .claude/state.mjs list audit)`);
	return { faults, notes };
}

/** A new or changed row checked whole, as check would: its shape among the others, then the labels it owes. */
export function refuse(r, others, marks = {}, { added = false } = {}) {
	const bad = shape(r, others);
	if (bad) return bad;
	// A new row names itself short now; an old one is given its short name once (list shorten), so a change to it is
	// never held for one.
	if (added && r.short == null) return `${r.id} has no short name: give "short", the row in at most ${SHORT} characters, for the one-line view`;
	const d = debt(r, marks);
	const need = owed(r).filter((k) => !(k === 'caught-by' ? d.catcher : d.measure));
	if (need.includes('caught-by')) return `${r.id} is ${r.tag} but names no catcher: set caught-by first (${CAUGHT.join(', ')})`;
	if (need.includes('measured')) return `${r.id} holds a number but names no measured label (${MEASURED.join(', ')})`;
	return null;
}

/** Change one field of a row from the command line; returns { row } or { why }. */
export function setField(r, field, value) {
	const v = value.trim();
	const out = { ...r };
	const yes = { yes: true, no: false, true: true, false: false };
	if (field === 'tag') {
		// A tag with no place keeps the row's place; "at -" clears it.
		const [t, ...at] = v.split(/\s+/);
		out.tag = t.toLowerCase();
		if (at.length === 1 && at[0] === '-') delete out.at;
		else if (at.length) out.at = at.join(' ');
	} else if (field === 'at') { if (v === '-') delete out.at; else out.at = v; }
	else if (field === 'caught-by') out.caught_by = v;
	else if (field === 'escaped') { if (!Object.hasOwn(yes, v)) return { why: 'escaped is yes or no' }; out.escaped = yes[v]; }
	else if (['title', 'short', 'severity', 'origin', 'measured', 'note', 'section', 'verify'].includes(field)) out[field] = v;
	else return { why: 'the field is one of tag, at, title, short, severity, origin, caught-by, escaped, measured, note, section, verify' };
	return { row: out };
}

// Which rows a roadmap step holds: a row's "at" names the step ("9", "build 9 (1.35.0)", "T5") or its release.
export const inStep = (r, s) => {
	const at = String(r.at || '').trim();
	if (!at) return false;
	const b = at.match(/^build (\S+)/i);
	return at === s.step || (b && b[1] === s.step) || (s.release && (at === s.release || at.includes(`(${s.release})`)));
};

/** The three generated views, as lines. */
export function views(rows, steps = []) {
	const roadmap = ['| Step | Release | What it carries | State | Open rows |', '|---|---|---|---|---|',
		...steps.map((s) => `| ${cell(s.step)} | ${cell(dash(s.release))} | ${cell(dash(s.carries))} | ${cell(dash(s.state))} | ${rows.filter((r) => !CLOSED.includes(r.tag) && inStep(r, s)).length} |`)];
	const counts = TAGS.map((t) => [t, rows.filter((r) => r.tag === t).length]).filter(([, n]) => n);
	const total = [`Total ${rows.length} rows${counts.length ? `: ${counts.map(([t, n]) => `${n} ${t}`).join(', ')}` : ''}.`];
	// TC3 (build 20): the rows view shows the open rows only, the one a thread reads at start; done and closed rows go
	// to the archive view, built from the same data, so each row is in exactly one of the two and none is lost.
	const table = (list) => {
		const t = [];
		for (const sec of [...new Set(list.map((r) => r.section || 'Rows'))]) {
			if (t.length) t.push('');
			// A section is a bold line, never a heading, so no reader of headings can take row text for its own.
			t.push(`**${cell(sec).replace(/\*/g, '\\*')}**`, '', '| ID | Item | Detail | Severity | Caught by | Status |', '|---|---|---|---|---|---|');
			for (const r of list.filter((x) => (x.section || 'Rows') === sec)) {
				const detail = Object.entries(r.detail || {}).map(([k, v]) => `${k}: ${v}`).join('; ');
				t.push(`| ${cell(r.id)} | ${cell(r.title)} | ${cell(dash(detail))} | ${r.severity} | ${r.caught_by || 'not set'}${r.escaped ? ' (escaped)' : ''} | ${tagText(r)}${r.note ? ` ${cell(r.note)}` : ''} |`);
			}
		}
		return t;
	};
	const out = table(rows.filter((r) => !CLOSED.includes(r.tag)));
	const archive = table(rows.filter((r) => CLOSED.includes(r.tag)));
	const sections = [...new Set(rows.map((r) => r.section || 'Rows'))];
	// K69: the checkbox view, the shape the projects' roadmaps had by hand: a bold line per section, a box per row.
	const boxes = [];
	for (const sec of sections) {
		if (boxes.length) boxes.push('');
		boxes.push(`**${cell(sec).replace(/\*/g, '\\*')}**`, '');
		for (const r of rows.filter((x) => (x.section || 'Rows') === sec)) boxes.push(`- [${TAG_BOX[r.tag]}] ${cell(r.id)} ${cell(r.title)}`);
	}
	return { roadmap, counts: total, rows: out.length ? out : ['No open rows.'], archive: archive.length ? archive : ['No done or closed rows.'], boxes: boxes.length ? boxes : ['No rows yet: add one with node .claude/state.mjs item add --from <file.json>.'] };
}

/**
 * TC2 (build 20): the status board, written from the list data by script: one column per tag in TAGS order, one card
 * per row, so the board never disagrees with the list (the hand-kept one differed on 18 of 276 cards). One page with
 * its data inside it, no outside script or style; every row text is shown as text.
 *
 * Returns:
 *     the page's HTML
 */
export function boardHtml(rows, title = 'Status board') {
	const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
	const columns = TAGS.map((tag) => ({ tag, cards: rows.filter((r) => r.tag === tag).map((r) => ({ id: r.id, text: r.short || r.title, severity: r.severity, at: r.at || '', section: r.section || '' })) })).filter((c) => c.cards.length);
	const data = JSON.stringify({ title, total: rows.length, columns }).replace(/</g, '\\u003c');
	const cols = columns.map((c) => `<section><h2>${esc(c.tag)} <span>${c.cards.length}</span></h2>${c.cards.map((k) => `<article><b>${esc(k.id)}</b> ${esc(k.text)}<small>${esc(k.severity)}${k.at ? ` | ${esc(k.at)}` : ''}</small></article>`).join('')}</section>`).join('\n');
	return [
		'<!doctype html>', '<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">', `<title>${esc(title)}</title>`,
		'<style>:root{--bg:#fff;--fg:#1a1a1a;--card:#f3f3f1;--muted:#666}@media (prefers-color-scheme:dark){:root{--bg:#161616;--fg:#eee;--card:#262626;--muted:#aaa}}',
		'body{margin:0;padding:16px;background:var(--bg);color:var(--fg);font:14px/1.4 system-ui,sans-serif}main{display:flex;gap:12px;overflow-x:auto;align-items:flex-start}',
		'section{min-width:240px;flex:1}h2{font-size:14px;text-transform:uppercase;letter-spacing:.04em}h2 span{color:var(--muted)}article{background:var(--card);border-radius:6px;padding:8px;margin:0 0 8px}small{display:block;color:var(--muted);margin-top:4px}</style></head>',
		`<body><h1>${esc(title)}</h1><p>${rows.length} rows, written from _List.jsonl by node .claude/state.mjs board; never edited by hand.</p><main>`, cols, '</main>',
		`<script type="application/json" id="board-data">${data}</script>`, '</body></html>', '',
	].join('\n');
}

/**
 * Every list block in a file: { name, begin, end }, or a reason the markers cannot be trusted. A marker sits alone on
 * its line at the left edge, in the exact form render writes; one indented, carrying other text, or inside fenced
 * code is refused, so a hand-written view can never pass as a generated one.
 */
export function blocksIn(text) {
	const lines = text.split(/\r?\n/);
	const found = [];
	let open = null;
	let fence = null;
	for (let i = 0; i < lines.length; i++) {
		const l = lines[i];
		const f = FENCE.exec(l);
		if (fence) { if (f && f[1] === fence) fence = null; if (MARKER.test(l)) return { why: `a list marker inside fenced code at line ${i + 1}` }; continue; }
		if (f) { fence = f[1]; continue; }
		if (!MARKER.test(l)) continue;
		const b = /^<!-- list:begin (\w+)(?::[^\n]*)? -->$/.exec(l);
		if (b && l !== BEGIN(b[1]) && l !== `<!-- list:begin ${b[1]} -->`) return { why: `the list marker at line ${i + 1} is not in the form render writes` };
		if (b) {
			if (open) return { why: `a list block opens inside the ${open.name} block` };
			if (!BLOCKS.includes(b[1])) return { why: `list block ${show(b[1])} is not one of ${BLOCKS.join(', ')}` };
			if (found.some((x) => x.name === b[1])) return { why: `two ${b[1]} list blocks` };
			open = { name: b[1], begin: i };
		} else if (l === END) {
			if (!open) return { why: 'a list block ends that never began' };
			found.push({ ...open, end: i });
			open = null;
		} else return { why: `the list marker at line ${i + 1} is not alone on its line at the left edge` };
	}
	if (open) return { why: `the ${open.name} list block never ends` };
	return { lines, crlf: /\r\n/.test(text), blocks: found };
}
