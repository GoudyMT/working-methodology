// The improvement list and the roadmap as data (T4 slice 2, 1.35.0); state.mjs runs it. On 1.34.0 the workbench list
// held 339 rows in 9 table shapes, no row said who caught it (J4) and no number said where it was measured (J3), and
// the counts were recounted by hand at every closeout. Now each row is one line of _List.jsonl with one tag, and the
// roadmap steps sit in _State.json; the roadmap, counts and rows views are generated between list markers.
//
// A row: { id, title, tag, at?, severity, origin?, caught_by?, escaped?, measured?, note?, section?, detail?, imported? }
//   tag        one of TAGS; "at" says where (a release for done, a step for later, a build for next)
//   origin     who found it: real-use (a project using the kit), owner, outside (another method), self (the kit on itself)
//   caught_by  which layer caught it (J4); a row closed by these commands must name one
//   measured   where its numbers come from (J3); a row with a number must name one
//   imported   set by import: the row owes its labels to the one-time audit (counted by check, not failed)
// A row changed by these commands keeps the imported mark, but closing it still needs a catcher.

export const LIST = '_List.jsonl';
export const TAGS = ['done', 'closed', 'now', 'next', 'later', 'after', 'separate', 'owner', 'standing', 'plan'];
const CLOSED = ['done', 'closed'];
export const ORIGINS = ['real-use', 'owner', 'outside', 'self'];
export const CAUGHT = ['sweep', 'ci', 'recall', 'plan-check', 'review', 'guard', 'owner', 'real-use', 'self'];
export const MEASURED = ['throwaway', 'real-use', 'ci', 'agent-report', 'estimate', 'quote'];
export const SEVERITIES = ['critical', 'high', 'medium', 'low', 'to set'];
const ID = /^[A-Za-z][A-Za-z0-9.-]{0,39}$/;
const BLOCKS = ['roadmap', 'counts', 'rows'];
const BEGIN = (name) => `<!-- list:begin ${name}: generated by .claude/state.mjs from ${LIST} and _State.json; change it with state.mjs, never by hand -->`;
const IS_BEGIN = /^<!-- list:begin (\w+)\b.*-->$/;
const IS_END = /^<!-- list:end -->$/;

/** The rows, or a reason the file is not a clean list. A missing file is an empty list with exists false. */
export function loadList(io) {
	const text = io.readText(LIST);
	if (text === null) return { rows: [], exists: false };
	const rows = [];
	const lines = text.split(/\r?\n/).filter((l) => l.trim());
	for (let i = 0; i < lines.length; i++) {
		let r;
		try { r = JSON.parse(lines[i]); } catch { return { why: `${LIST} line ${i + 1} is not JSON` }; }
		const bad = shape(r, rows);
		if (bad) return { why: `${LIST} line ${i + 1}: ${bad}` };
		rows.push(r);
	}
	return { rows, exists: true };
}

/** What is wrong with a row's shape (not its owed labels), or null. */
function shape(r, rows) {
	if (!r || typeof r !== 'object' || Array.isArray(r)) return 'not an object';
	if (typeof r.id !== 'string' || !ID.test(r.id)) return `the id ${JSON.stringify(String(r.id)).slice(0, 40)} is not letters, digits, dots and dashes`;
	if (rows.some((x) => x.id === r.id)) return `${r.id} is given twice`;
	if (typeof r.title !== 'string' || !r.title.trim()) return `${r.id} has no title`;
	if (!TAGS.includes(r.tag)) return `${r.id}: tag "${String(r.tag)}" is not one of ${TAGS.join(', ')}`;
	if (!SEVERITIES.includes(r.severity)) return `${r.id}: severity "${String(r.severity)}" is not one of ${SEVERITIES.join(', ')}`;
	if (r.origin != null && !ORIGINS.includes(r.origin)) return `${r.id}: origin "${String(r.origin)}" is not one of ${ORIGINS.join(', ')}`;
	if (r.caught_by != null && !CAUGHT.includes(r.caught_by)) return `${r.id}: caught_by "${String(r.caught_by)}" is not one of ${CAUGHT.join(', ')}`;
	if (r.measured != null && !MEASURED.includes(r.measured)) return `${r.id}: measured "${String(r.measured)}" is not one of ${MEASURED.join(', ')}`;
	if (r.escaped != null && typeof r.escaped !== 'boolean') return `${r.id}: escaped is not true or false`;
	for (const k of ['at', 'note', 'section']) if (r[k] != null && typeof r[k] !== 'string') return `${r.id}: ${k} is not text`;
	if (r.detail != null && (typeof r.detail !== 'object' || Array.isArray(r.detail) || Object.values(r.detail).some((v) => typeof v !== 'string'))) return `${r.id}: detail is not a set of text cells`;
	return null;
}

// J3: a number someone measured, as against an id, a version, a date, a time or a file line.
const NOT_MEASURES = [/\b\d{4}-\d{2}-\d{2}\b/g, /\b\d{1,2}:\d{2}(:\d{2})?\b/g, /\bv?\d+\.\d+(\.\d+)+\b/g, /\b[A-Za-z]+[-.]?\d+[a-z]?(\.\d+)?(-\d+)?\b/g, /(#|PR |pr |build |step |rule |line |row |item |stage |part |option |trial |round |run )\d+\b/g, /:\d+(-\d+)?\b/g];
const textOf = (r) => [r.title, r.note || '', ...Object.values(r.detail || {})].join(' ');
export const holdsNumber = (r) => /\d/.test(NOT_MEASURES.reduce((t, re) => t.replace(re, ' '), textOf(r)));

/** The labels a row still owes: a catcher on a closed row, a measure label on a number. */
function owed(r) {
	const out = [];
	if (CLOSED.includes(r.tag) && !r.caught_by) out.push('caught-by');
	if (holdsNumber(r) && !r.measured) out.push('measured');
	return out;
}

const tagText = (r) => `**[${r.tag.toUpperCase()}${r.at ? ` ${r.at}` : ''}]**`;
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const dash = (s) => (String(s ?? '').trim() ? s : '-');

// A markdown table row's cells, split on pipes that are not escaped.
const cells = (line) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|'));
const TAG_IN = /\*\*\[([A-Za-z]+)(?: ([^\]]*))?\]\*\*/;
const sev = (s) => { const m = String(s).toLowerCase().match(/\b(critical|high|medium|low)\b/); return m ? m[1] : 'to set'; };

/**
 * Read a markdown list whole: every table whose header has an ID and a Status column becomes rows, under the section
 * heading it sits in; a table headed Build | Release | ... | State becomes the roadmap steps. It refuses the whole file
 * on any row it cannot move (no tag, an unknown tag, an id twice), so a half list is never written.
 */
export function parseMarkdown(text) {
	const lines = text.replace(/\r\n/g, '\n').split('\n');
	const rows = [];
	const steps = [];
	const faults = [];
	let section = '';
	for (let i = 0; i < lines.length; i++) {
		const l = lines[i];
		const h = l.match(/^#{2,3} (.+)$/);
		if (h) { section = h[1].trim(); continue; }
		if (!/^\|/.test(l) || !/^\|[\s:|-]+\|$/.test(lines[i + 1] || '')) continue;
		const head = cells(l);
		const body = [];
		const lineNo = [];
		for (i += 2; i < lines.length && /^\|/.test(lines[i]); i++) { body.push(cells(lines[i])); lineNo.push(i + 1); }
		i--;
		const col = (re) => head.findIndex((c) => re.test(c));
		if (/^build$/i.test(head[0]) && /^release$/i.test(head[1] || '')) {
			const st = col(/^state$/i);
			const carries = head.findIndex((c, k) => k > 1 && k !== st);
			for (const c of body) steps.push({ step: c[0], release: c[1] || '', carries: c[carries] || '', state: c[st] || '' });
			continue;
		}
		const id = col(/^id$/i);
		const status = col(/^status$/i);
		if (id !== 0 || status < 0) continue;
		const title = id + 1;
		const severity = col(/^severity/i);
		body.forEach((c, n) => {
			const where = `line ${lineNo[n]}`;
			const m = TAG_IN.exec(c[status] || '');
			if (!m) { faults.push(`${c[id]} has no tag: its status must start with **[TAG ...]** (${where})`); return; }
			const tag = m[1].toLowerCase() === 'shipped' ? 'done' : m[1].toLowerCase();
			if (!TAGS.includes(tag)) { faults.push(`${c[id]}: tag ${m[1]} is not one of ${TAGS.map((t) => t.toUpperCase()).join(', ')} (${where})`); return; }
			const detail = {};
			head.forEach((name, k) => { if (![id, title, status].includes(k) && c[k] && c[k] !== '-' && !(k === severity && SEVERITIES.includes(c[k]))) detail[name] = c[k]; });
			const r = { id: c[id], title: c[title] || '', tag, severity: severity >= 0 ? sev(c[severity]) : 'to set', section, imported: true };
			if (m[2]) r.at = m[2].trim();
			const note = (c[status] || '').replace(m[0], '').trim();
			if (note) r.note = note;
			if (Object.keys(detail).length) r.detail = detail;
			const bad = shape(r, rows);
			if (bad) { faults.push(`${bad} (${where})`); return; }
			rows.push(r);
		});
	}
	if (!rows.length && !faults.length) faults.push('no table with an ID column first and a Status column was found');
	return { rows, steps, faults };
}

export const serialize = (rows) => rows.map((r) => JSON.stringify(r)).join('\n') + (rows.length ? '\n' : '');

// T11: at the same severity, a row from a real project ranks above one the owner asked for, then another method's,
// then the kit's own finds.
const rank = (r) => [SEVERITIES.indexOf(r.severity), r.origin ? ORIGINS.indexOf(r.origin) : ORIGINS.length];
export function ranked(rows) {
	return rows.filter((r) => !CLOSED.includes(r.tag)).map((r, i) => [r, i]).sort(([a, i], [b, j]) => {
		const [x, y] = [rank(a), rank(b)];
		return x[0] - y[0] || x[1] - y[1] || i - j;
	}).map(([r]) => r);
}
export const line = (r) => `${r.id} ${tagText(r).replace(/\*\*/g, '')} ${r.severity}${r.origin ? `, ${r.origin}` : ''}: ${r.title}`;

/** J4 and T11 at a glance: who caught the closed rows, how many escaped a gate, and found-to-shipped by origin. */
export function caught(rows) {
	const closed = rows.filter((r) => CLOSED.includes(r.tag));
	const by = CAUGHT.map((c) => [c, closed.filter((r) => r.caught_by === c).length]).filter(([, n]) => n);
	const none = closed.filter((r) => !r.caught_by).length;
	const out = [`Caught by: ${by.map(([c, n]) => `${c} ${n}`).join(', ') || 'none named'}${none ? `; not named ${none}` : ''}; escaped a gate: ${closed.filter((r) => r.escaped).length} of ${closed.length}`];
	const origins = [...ORIGINS, null].map((o) => {
		const mine = rows.filter((r) => (r.origin || null) === o);
		const n = (t) => mine.filter((r) => r.tag === t).length;
		return mine.length ? `${o || 'not set'} ${mine.length} found, ${n('done')} done, ${n('closed')} closed, ${mine.length - n('done') - n('closed')} open` : null;
	}).filter(Boolean);
	out.push(`Found to shipped by origin: ${origins.join('; ') || 'no rows'}`);
	return out;
}

/** The rows still owed a label, one line each: the one-time catch-rate and measure audit. */
export const audit = (rows) => rows.flatMap((r) => {
	const need = [...(r.origin ? [] : ['origin']), ...owed(r)];
	return need.length ? [`${r.id} owes ${need.join(', ')}: ${r.title.slice(0, 80)}`] : [];
});

/** Faults and notes for check: labels owed by rows changed or added since the import fail; imported ones are counted. */
export function faultsOf(rows) {
	const faults = [];
	let noCatch = 0;
	let noMeasure = 0;
	for (const r of rows) {
		for (const k of owed(r)) {
			if (r.imported) { if (k === 'caught-by') noCatch++; else noMeasure++; continue; }
			faults.push(k === 'measured' ? `${r.id} holds a number but names no measured label (${MEASURED.join(', ')}): node .claude/state.mjs item set ${r.id} measured <label>` : `${r.id} is ${r.tag} but names no catcher: node .claude/state.mjs item set ${r.id} caught-by <${CAUGHT.join('|')}>`);
		}
	}
	const notes = [];
	if (noCatch) notes.push(`${noCatch} imported done or closed row(s) name no catcher (node .claude/state.mjs list audit)`);
	if (noMeasure) notes.push(`${noMeasure} imported row(s) hold a number with no measure label (node .claude/state.mjs list audit)`);
	return { faults, notes };
}

/** A new or changed row checked whole, as check would: its shape among the others, then the labels it owes. */
export function refuse(r, others, { closing = false } = {}) {
	const bad = shape(r, others);
	if (bad) return bad;
	const need = owed(r).filter((k) => !r.imported || (k === 'caught-by' && closing));
	if (need.includes('caught-by')) return `${r.id} is ${r.tag} but names no catcher: set caught-by first (${CAUGHT.join(', ')})`;
	if (need.includes('measured')) return `${r.id} holds a number but names no measured label (${MEASURED.join(', ')})`;
	return null;
}

/** Change one field of a row from the command line; returns { row } or { why }. */
export function setField(r, field, value) {
	const v = value.trim();
	const out = { ...r };
	const yes = { yes: true, no: false, true: true, false: false };
	if (field === 'tag') {
		const [t, ...at] = v.split(/\s+/);
		out.tag = t.toLowerCase();
		if (at.length) out.at = at.join(' '); else delete out.at;
	} else if (field === 'caught-by') out.caught_by = v;
	else if (field === 'escaped') { if (!(v in yes)) return { why: 'escaped is yes or no' }; out.escaped = yes[v]; }
	else if (['title', 'severity', 'origin', 'measured', 'note', 'section'].includes(field)) out[field] = v;
	else return { why: `the field is one of tag, title, severity, origin, caught-by, escaped, measured, note, section` };
	return { row: out };
}

// Which rows a roadmap step holds: a row's "at" names the step ("9", "build 9 (1.35.0)", "T5") or its release.
const inStep = (r, s) => {
	const at = String(r.at || '').trim();
	if (!at) return false;
	const b = at.match(/^build (\S+)/i);
	return at === s.step || (b && b[1] === s.step) || (s.release && (at === s.release || at.includes(`(${s.release})`)));
};

/** The three generated views, as lines. */
export function views(rows, steps = []) {
	const roadmap = ['| Step | Release | What it carries | State | Open rows |', '|---|---|---|---|---|',
		...steps.map((s) => `| ${cell(s.step)} | ${cell(dash(s.release))} | ${cell(dash(s.carries))} | ${cell(dash(s.state))} | ${rows.filter((r) => !CLOSED.includes(r.tag) && inStep(r, s)).length} |`)];
	const counts = TAGS.map((t) => [t, rows.filter((r) => r.tag === t).length]).filter(([, n]) => n);
	const total = [`Total ${rows.length} rows${counts.length ? `: ${counts.map(([t, n]) => `${n} ${t}`).join(', ')}` : ''}.`];
	const out = [];
	const sections = [...new Set(rows.map((r) => r.section || 'Rows'))];
	for (const sec of sections) {
		if (out.length) out.push('');
		out.push(`### ${sec}`, '', '| ID | Item | Detail | Severity | Caught by | Status |', '|---|---|---|---|---|---|');
		for (const r of rows.filter((x) => (x.section || 'Rows') === sec)) {
			const detail = Object.entries(r.detail || {}).map(([k, v]) => `${k}: ${v}`).join('; ');
			out.push(`| ${cell(r.id)} | ${cell(r.title)} | ${cell(dash(detail))} | ${r.severity} | ${r.caught_by || 'not set'}${r.escaped ? ' (escaped)' : ''} | ${tagText(r)}${r.note ? ` ${cell(r.note)}` : ''} |`);
		}
	}
	return { roadmap, counts: total, rows: out.length ? out : ['No rows.'] };
}

/** Every list block in a file: { name, begin, end }, or a reason the markers do not pair. */
export function blocksIn(text) {
	const lines = text.split(/\r?\n/);
	const found = [];
	let open = null;
	for (let i = 0; i < lines.length; i++) {
		const b = IS_BEGIN.exec(lines[i]);
		if (b) {
			if (open) return { why: `a list block opens inside the ${open.name} block` };
			if (!BLOCKS.includes(b[1])) return { why: `list block "${b[1]}" is not one of ${BLOCKS.join(', ')}` };
			if (found.some((f) => f.name === b[1])) return { why: `two ${b[1]} list blocks` };
			open = { name: b[1], begin: i };
		} else if (IS_END.test(lines[i])) {
			if (!open) return { why: 'a list block ends that never began' };
			found.push({ ...open, end: i });
			open = null;
		}
	}
	if (open) return { why: `the ${open.name} list block never ends` };
	return { lines, crlf: /\r\n/.test(text), blocks: found };
}
